#!/usr/bin/env node
/**
 * Generates the Khmer copy review sheet.
 *
 * The Khmer strings must be checked by a native speaker before release — no test
 * can establish that wording is natural, or that the tone is right for a merchant
 * asking a neighbour for money. This script turns that from "read the codebase"
 * into "read one table", which is the difference between a review happening and
 * not happening.
 *
 *     node scripts/generate-khmer-review.mjs
 *
 * Regenerate after changing any string; the output is committed so corrections can
 * be diffed and discussed.
 */

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const { km, en } = require(join(rootDir, 'packages/localization/dist/index.js'));
const { REMINDER_TEMPLATES, composeReminderMessage } = require(
  join(rootDir, 'packages/domain/dist/index.js'),
);

/** Where each key prefix appears, in words a non-developer can act on. */
const SECTIONS = [
  ['common.', 'Buttons and words used everywhere'],
  ['nav.', 'Bottom navigation'],
  ['home.', 'Home dashboard'],
  ['customers.', 'Customer list, add and detail'],
  ['transactions.', 'Transaction history'],
  ['form.', 'Recording a debt or a payment'],
  ['status.', 'Status badges on a debt'],
  ['reversal.', 'Cancelling a transaction'],
  ['reminders.', 'Reminders and the message sent to a customer'],
  ['lists.', 'Due today and overdue lists'],
  ['sync.', 'Saving and uploading'],
  ['restore.', 'Restoring on a new phone'],
  ['reports.', 'Reports'],
  ['export.', 'Exporting data'],
  ['statement.', 'Customer statement (PDF)'],
  ['onboarding.', 'First-time setup'],
  ['auth.', 'Signing in'],
  ['security.', 'PIN and biometric lock'],
  ['settings.', 'Settings'],
  ['diagnostics.', 'Technical details screen'],
  ['error.', 'Error messages'],
  ['validation.', 'Form validation messages'],
  ['privacy.', 'Privacy explanations'],
];

/** Long enough to risk clipping on a 5" 720p screen. */
const LONG_STRING_THRESHOLD = 60;

/** Deliberately not Khmer. */
const PROPER_NOUNS = new Set(['form.paymentMethod.khqr', 'export.csv', 'export.pdf']);

const keys = Object.keys(km);

function escapeCell(value) {
  return value.replace(/\|/g, '\\|').replace(/\n/g, '<br>');
}

function isPluralPair(key) {
  return key.endsWith('_one') || key.endsWith('_other');
}

const lines = [];

lines.push('# Khmer copy review');
lines.push('');
lines.push('> Generated by `node scripts/generate-khmer-review.mjs`. Do not edit by hand —');
lines.push('> change `packages/localization/src/messages/km.ts` and regenerate.');
lines.push('');
lines.push('**This is a release blocker.** Every Khmer string below was written to be correct');
lines.push('and idiomatic, but none has been checked by a native speaker. No automated test');
lines.push('can tell us whether the wording sounds natural to a Cambodian shop owner, or');
lines.push('whether the tone is right for asking a neighbour about money.');
lines.push('');

lines.push('## What to look for');
lines.push('');
lines.push('1. **Does it sound like a person?** These are read by shopkeepers, not accountants.');
lines.push('2. **Is the tone right?** Reminder messages especially must feel polite and');
lines.push('   unembarrassing. Nothing here should ever pressure or shame a customer.');
lines.push('3. **Is the vocabulary the one merchants actually use** for credit and repayment?');
lines.push('4. **Is anything ambiguous** out of context, as a button label with no sentence');
lines.push('   around it?');
lines.push('');

lines.push('## Please do NOT "fix" these');
lines.push('');
lines.push('Khmer has no grammatical plural, so keys ending `_one` and `_other` are');
lines.push('**intentionally identical**. English needs two forms ("1 customer" / "3');
lines.push('customers"); Khmer uses one. Making them differ would be wrong.');
lines.push('');
lines.push('`KHQR`, `CSV` and `PDF` are proper nouns and stay in Latin script.');
lines.push('');

// --- Customer-facing messages, reviewed first --------------------------------
// These are the only strings a CUSTOMER ever sees, and they are sent while asking
// someone for money. Tone matters more here than anywhere else in the product, so
// they lead the sheet rather than being buried among UI labels.
lines.push('## Messages sent to customers — review these first');
lines.push('');
lines.push('These are the only strings a **customer** ever reads. The merchant sees the');
lines.push('message, may edit it, and chooses whether to send it — the app never sends');
lines.push('anything on its own. They must feel polite and must never embarrass anyone.');
lines.push('');
lines.push('Shown filled in with a realistic example so the tone can be judged as sent.');
lines.push('');

for (const template of REMINDER_TEMPLATES.filter((entry) => entry.locale === 'km')) {
  const example = composeReminderMessage({
    locale: 'km',
    tone: template.tone,
    customerName: 'សុខ ដារា',
    shopName: 'ហាងម្ដាយថាន',
    outstandingMinor: 50000,
    currency: 'KHR',
    dueDate: template.requiresDueDate ? '2026-08-10' : null,
    merchantPhone: '012 345 678',
  });

  lines.push(`**\`${template.id}\`** — ${template.tone.toLowerCase()}, ` +
    `${template.requiresDueDate ? 'with' : 'without'} a due date`);
  lines.push('');
  lines.push('```');
  lines.push(example);
  lines.push('```');
  lines.push('');
}

lines.push('Defined in `packages/domain/src/reminders/templates.ts`. A test asserts none of');
lines.push('them mentions police, courts, blacklists or shaming — please flag anything that');
lines.push('reads as pressure even if it passes that check.');
lines.push('');

// --- Attention list ----------------------------------------------------------
const longStrings = keys
  .filter((key) => km[key].length > LONG_STRING_THRESHOLD)
  .sort((a, b) => km[b].length - km[a].length);

lines.push('## Needs the most attention');
lines.push('');
lines.push('These are the longest strings. Khmer does not put spaces between words inside a');
lines.push('phrase, so a long run cannot wrap and may be clipped on a small screen. Please');
lines.push('check both the wording **and** whether a shorter phrasing would carry the same');
lines.push('meaning.');
lines.push('');
lines.push('| Key | Khmer | Chars |');
lines.push('|---|---|---|');
for (const key of longStrings) {
  lines.push(`| \`${key}\` | ${escapeCell(km[key])} | ${km[key].length} |`);
}
lines.push('');

// --- Full sheet --------------------------------------------------------------
lines.push('## Every string, by screen');
lines.push('');
lines.push('Leave the **Correction** column empty where the Khmer is already right.');
lines.push('');

const covered = new Set();

for (const [prefix, title] of SECTIONS) {
  const sectionKeys = keys.filter((key) => key.startsWith(prefix));
  if (sectionKeys.length === 0) continue;
  sectionKeys.forEach((key) => covered.add(key));

  lines.push(`### ${title}`);
  lines.push('');
  lines.push('| Key | English | Khmer | Correction |');
  lines.push('|---|---|---|---|');

  for (const key of sectionKeys) {
    const note = isPluralPair(key)
      ? ' _(plural pair — identical on purpose)_'
      : PROPER_NOUNS.has(key)
        ? ' _(proper noun)_'
        : '';
    lines.push(
      `| \`${key}\`${note} | ${escapeCell(en[key])} | ${escapeCell(km[key])} | |`,
    );
  }
  lines.push('');
}

const uncovered = keys.filter((key) => !covered.has(key));
if (uncovered.length > 0) {
  lines.push('### Other');
  lines.push('');
  lines.push('| Key | English | Khmer | Correction |');
  lines.push('|---|---|---|---|');
  for (const key of uncovered) {
    lines.push(`| \`${key}\` | ${escapeCell(en[key])} | ${escapeCell(km[key])} | |`);
  }
  lines.push('');
}

lines.push('---');
lines.push('');
lines.push(`${keys.length} strings. Corrections go into`);
lines.push('`packages/localization/src/messages/km.ts`; the English file is typed against it,');
lines.push('so a key cannot be lost in the process.');

const outputPath = join(rootDir, 'docs/product/khmer-copy-review.md');
writeFileSync(outputPath, `${lines.join('\n')}\n`, 'utf8');

console.log(`Wrote docs/product/khmer-copy-review.md`);
console.log(`  ${keys.length} strings across ${SECTIONS.length} sections`);
console.log(`  ${longStrings.length} flagged as long enough to risk clipping`);
